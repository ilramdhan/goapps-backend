    v_md_total     INT;
    v_md_found     INT;
    v_md_applied   INT;
BEGIN
    -- (1) overrides ---------------------------------------------------------
    CREATE TEMP TABLE tmp_580_override_resolved ON COMMIT DROP AS
    SELECT o.cpm_product_sys_id AS owner_id,
           s.rm_type,
           r.cpm_product_sys_id AS rm_id,
           g.group_code         AS rm_group,
           s.denier,
